import { formatCurrency } from "./format";
import { RECOMMENDED_ACTIONS } from "./recommendedActions";
import type { AnalysisSummaryResponse, DiscrepancyDetailResponse } from "../types/results";

const CATEGORY_LABELS: Record<string, string> = {
  MISSING_SETTLEMENT: "Missing settlement",
  UNEXPECTED_SETTLEMENT: "Unexpected settlement",
  INCORRECT_COMMISSION: "Incorrect commission",
  SETTLEMENT_AMOUNT_MISMATCH: "Settlement amount mismatch",
  CANCELLED_AFTER_PREPARATION: "Cancelled after preparation",
};

/**
 * Client-side by design, not a new backend endpoint - every field this
 * needs (order_reference, category, amount) is already sitting in the
 * Results page's own state from the /discrepancies fetch, and the
 * recommended-action text only exists in the frontend to begin with
 * (lib/recommendedActions.ts). A backend PDF endpoint would mean either
 * duplicating that copy server-side or passing it back up to the API
 * just to have it echoed into a file - more moving parts for a document
 * whose entire source data is already in memory. Runs entirely in the
 * browser: nothing about the report leaves the device except the
 * download itself.
 *
 * Includes every discrepancy, not just the page's top-10 "High Priority
 * Cases" - a claim sent to a platform needs the complete list, not the
 * highest-severity subset shown for the page's own UI purposes.
 *
 * jsPDF and jspdf-autotable are imported dynamically, not at module top
 * level - jsPDF bundles html2canvas + dompurify internally for an
 * HTML-rendering feature this file never calls, and eagerly importing
 * it added ~450KB to the main bundle that every visitor would download
 * just to see the login page. This way that weight only loads the
 * moment someone actually clicks the button.
 */
export async function generateDisputeReport(
  summary: AnalysisSummaryResponse,
  discrepancies: DiscrepancyDetailResponse[],
  period: { periodStart: string; periodEnd: string },
): Promise<void> {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);

  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Reconciliation Dispute Report", margin, 20);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  let y = 28;

  const claimant = summary.restaurant_name ?? "Restaurant";
  doc.text(`Submitted by: ${claimant}`, margin, y);
  y += 5;
  doc.text(`Period covered: ${period.periodStart} to ${period.periodEnd}`, margin, y);
  y += 5;
  doc.text(`Generated: ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`, margin, y);
  y += 5;
  if (summary.contact_email || summary.whatsapp_number) {
    const contactParts = [summary.contact_email, summary.whatsapp_number].filter(Boolean);
    doc.text(`Contact: ${contactParts.join(" · ")}`, margin, y);
    y += 5;
  }

  y += 4;
  doc.setDrawColor(220, 220, 220);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(20, 20, 20);
  doc.text(
    `Total claimed: ${formatCurrency(summary.total_potential_revenue_leakage, summary.currency)} across ${discrepancies.length} ${discrepancies.length === 1 ? "case" : "cases"}`,
    margin,
    y,
  );
  y += 8;

  autoTable(doc, {
    startY: y,
    head: [["Order reference", "Category", "Amount", "Requested action"]],
    body: discrepancies.map((item) => [
      item.order_reference ?? "—",
      CATEGORY_LABELS[item.category] ?? item.category,
      formatCurrency(item.estimated_loss, summary.currency),
      RECOMMENDED_ACTIONS[item.category],
    ]),
    styles: { fontSize: 8, cellPadding: 3, overflow: "linebreak" },
    headStyles: { fillColor: [181, 98, 44], textColor: 255 },
    columnStyles: {
      0: { cellWidth: 28 },
      1: { cellWidth: 32 },
      2: { cellWidth: 22 },
      3: { cellWidth: "auto" },
    },
    margin: { left: margin, right: margin },
  });

  const pageCount = doc.getNumberOfPages();
  for (let page = 1; page <= pageCount; page++) {
    doc.setPage(page);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text(
      "Generated by ReconFlow AI - reconciliation figures are estimates pending platform review.",
      margin,
      doc.internal.pageSize.getHeight() - 10,
    );
  }

  const safeName = claimant.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
  doc.save(`dispute-report-${safeName}-${period.periodStart}.pdf`);
}
